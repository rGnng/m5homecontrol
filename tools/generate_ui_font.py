#!/usr/bin/env python3
"""Build exact 2x bitmap pixels from the supplied BoutiqueBitmap9x9 1.6 TTF."""
import argparse
import hashlib
import io
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/fonts'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True)
    args = parser.parse_args()
    manifest = json.loads((ASSETS/'source.json').read_text())
    raw = args.font.read_bytes()
    if hashlib.sha256(raw).hexdigest() != manifest['sha256']:
        raise ValueError('Source font checksum mismatch')
    font = TTFont(io.BytesIO(raw))
    assert font['head'].unitsPerEm == 1000 and font['OS/2'].usWeightClass == 400
    cmap = font.getBestCmap()
    # One source dot is 100 design units. Preserve the font's 10-dot spacing
    # grid and leave an extra row for descenders. Hinting must not shift dots.
    font['glyf'].removeHinting()
    for tag in ['fpgm','prep','cvt ','gasp']:
        if tag in font: del font[tag]
    buffer = io.BytesIO()
    font.save(buffer)
    raster = ImageFont.truetype(io.BytesIO(buffer.getvalue()), 10)
    codes, advances, bitmap, omitted = [], bytearray(), bytearray(), []
    for cp in sorted(cp for cp in cmap if 0x20 <= cp < 0xffff):
        name = cmap[cp]
        glyph = font['glyf'][name]
        advance = round(font['hmtx'].metrics[name][0] / 100)
        # Rare tall accents, negative overhangs and double-em symbols cannot
        # fit this menu cell. Use the missing-glyph marker for those characters.
        if advance > 10 or (glyph.numberOfContours and
            (glyph.xMin < -2 or glyph.xMax > 1002 or glyph.yMin < -302 or glyph.yMax > 802)):
            omitted.append(cp)
            continue
        canvas = Image.new('L', (12,13), 0)
        ImageDraw.Draw(canvas).text((1,9), chr(cp), font=raster, fill=255, anchor='ls')
        canvas = canvas.point(lambda value: 255 if value >= 128 else 0)
        native = canvas.crop((1,1,11,12))
        # Detect any rasterized ink outside the selected cell rather than clip it.
        outside = canvas.copy()
        ImageDraw.Draw(outside).rectangle((1,1,10,11), fill=0)
        if outside.getbbox():
            omitted.append(cp)
            continue
        tile = native.resize((20,22), Image.Resampling.NEAREST)
        codes.append(cp)
        advances.append(advance * 2)
        for y in range(22):
            row = sum(1 << (23-x) for x in range(20) if tile.getpixel((x,y)))
            bitmap.extend(row.to_bytes(3,'big'))
    assert all(cp in codes for cp in range(0x20,0x7f))
    assert all(cp in codes for cp in cmap if 0x3041 <= cp <= 0x30ff)
    assert ord('□') in codes
    codes.append(0xffff)
    advances.append(20)
    bitmap.extend(bytes(66))
    header = f'''#pragma once
#include <cstddef>
#include <cstdint>
// Generated by tools/generate_ui_font.py; see assets/fonts/README.md.
static constexpr size_t UI_FONT_GLYPH_COUNT = {len(codes)};
static constexpr size_t UI_FONT_WIDTH = 20;
static constexpr size_t UI_FONT_HEIGHT = 22;
static constexpr size_t UI_FONT_BASELINE = 16;
static constexpr size_t UI_FONT_ROW_BYTES = 3;
static constexpr size_t UI_FONT_GLYPH_BYTES = UI_FONT_ROW_BYTES * UI_FONT_HEIGHT;
extern const uint16_t uiFontCodepoints[UI_FONT_GLYPH_COUNT];
extern const uint8_t uiFontAdvances[UI_FONT_GLYPH_COUNT];
extern const uint8_t uiFontBitmap[UI_FONT_GLYPH_COUNT * UI_FONT_GLYPH_BYTES];
'''
    (ROOT/'include/ui_font_data.h').write_text(header)
    source = '''// Remote Dot 2x bitmap derivative; source terms: assets/fonts/licenses/.
#include "ui_font_data.h"
#include "ui_font.h"
#include <algorithm>
#ifdef ARDUINO
#include <pgmspace.h>
#else
#define PROGMEM
#endif
'''
    for declaration, values, digits in [
        ('uint16_t uiFontCodepoints[UI_FONT_GLYPH_COUNT]',codes,4),
        ('uint8_t uiFontAdvances[UI_FONT_GLYPH_COUNT]',advances,2),
        ('uint8_t uiFontBitmap[UI_FONT_GLYPH_COUNT * UI_FONT_GLYPH_BYTES]',bitmap,2),
    ]:
        source += f'const {declaration} PROGMEM = {{\n'
        for i in range(0,len(values),16):
            source += '    '+', '.join(f'0x{x:0{digits}x}' for x in values[i:i+16])+',\n'
        source += '};\n'
    source += '''
static const uint16_t* findGlyph(uint32_t cp) {
    if (cp >= 0xffff) return nullptr;
    const auto* end = uiFontCodepoints + UI_FONT_GLYPH_COUNT - 1;
    const auto* found = std::lower_bound(uiFontCodepoints, end, (uint16_t)cp);
    return found != end && *found == cp ? found : nullptr;
}
bool uiFontContains(uint32_t cp) { return findGlyph(cp) != nullptr; }
uint8_t uiFontAdvance(uint32_t cp) {
    const auto* found = findGlyph(cp);
    return found ? uiFontAdvances[found - uiFontCodepoints] : UI_FONT_WIDTH;
}
UiFontInkBounds uiFontInkBounds(uint32_t cp) {
    const auto* found = findGlyph(cp);
    if (!found) return {0, 0, 0, 0};
    const auto* tile = uiFontBitmap + (found - uiFontCodepoints) * UI_FONT_GLYPH_BYTES;
    int left = UI_FONT_WIDTH, top = UI_FONT_HEIGHT, right = -1, bottom = -1;
    for (int y=0; y<int(UI_FONT_HEIGHT); ++y) {
        for (int x=0; x<int(UI_FONT_WIDTH); ++x) {
            if (!(tile[y * UI_FONT_ROW_BYTES + x/8] & (0x80 >> (x%8)))) continue;
            left = std::min(left, x); top = std::min(top, y);
            right = std::max(right, x); bottom = std::max(bottom, y);
        }
    }
    return right < 0 ? UiFontInkBounds{0, 0, 0, 0}
                     : UiFontInkBounds{left, top, right-left+1, bottom-top+1};
}
'''
    (ROOT/'src/ui_font_data.cpp').write_text(source)
    (ASSETS/'omitted.txt').write_text('\n'.join(f'U+{cp:04X}' for cp in omitted)+'\n')
    print(f'Generated {len(codes)-1} glyphs with exact 2x dots; {len(omitted)} oversized glyphs omitted; '
          f'{len(bitmap)+len(advances)+len(codes)*2:,} font bytes')

if __name__ == '__main__':
    main()
